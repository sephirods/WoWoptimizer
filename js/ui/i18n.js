try {
  const savedLang = localStorage.getItem('wow_lang');
  if (savedLang === 'es' || savedLang === 'mx' || savedLang === 'en') {
    currentLang = savedLang;
  } else {
    currentLang = detectBrowserLanguage();
  }
} catch (e) {
  currentLang = detectBrowserLanguage();
}

